export function allPets(importedPets: InstalledPet[]): InstalledPet[] {
  const pets = new Map(BUNDLED_PETS.map((pet) => [pet.slug, pet]));
  for (const pet of importedPets) {
    pets.set(pet.slug, pet);
  }
  return [...pets.values()];
}
